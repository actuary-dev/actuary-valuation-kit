"""Generate the public schema reference; --check rejects stale pages."""

import argparse
import json
from pathlib import Path

import polars as pl

from avk.inputs.public_formats import PUBLIC_READERS
from avk.inputs.registry import InputSpec, Location
from avk.products.registry import ProductRegistry
from avk.runs.config import RunConfig

ROOT = Path(__file__).resolve().parents[1]


def pages():
    result = {}
    for label, model in (("run-file", RunConfig), ("inputs", InputSpec), ("location", Location)):
        schema = model.model_json_schema(by_alias=True)
        lines = [
            f"# {label.replace('-', ' ').title()} schema",
            "",
            "Generated by `uv run python scripts/generate_reference.py`; do not edit.",
            "See [how-tos](../how-tos.md) for conditional settings and complete examples.",
            "",
            "| Key | Required | Type / constraints / default |",
            "|---|---|---|",
        ]
        required = schema.get("required", [])
        for key, value in schema["properties"].items():
            spec = {k: v for k, v in value.items() if k != "title"}
            text = json.dumps(spec, sort_keys=True).replace("|", r"\|")
            lines.append(f"| `{key}` | {'yes' if key in required else 'no'} | `{text}` |")
        lines += [
            "",
            "Full JSON Schema (including nested definitions):",
            "",
            "```json",
            json.dumps(schema, indent=2, sort_keys=True),
            "```",
            "",
        ]
        result[f"{label}.md"] = "\n".join(lines)
    lines = [
        "# Table format registry",
        "",
        "Generated from the built-in reader registry; do not edit.",
        "",
        "Column layouts, units and boundary rules: [public formats](../inputs/public-formats.md).",
        "The format is selected by `Inputs.Replace.<logical table>.Format`.",
        "",
        "| Format | Reader |",
        "|---|---|",
    ]
    for name, reader in sorted(PUBLIC_READERS.items()):
        lines.append(f"| `{name}` | `{reader.__module__}.{reader.__name__}` |")
    result["table-formats.md"] = "\n".join(lines) + "\n"
    lines = [
        "# Output columns",
        "",
        "Generated from product output schemas and the approved public reporting schemas.",
        "Do not edit. Amount columns are in the input currency; rates are fractions.",
        "See [output conventions](../output-conventions.md) before summing or taking ratios.",
        "A source identifies the formula column; basis selects its evaluation assumptions.",
        "Keys identify rows. Aggregates sum amounts; book ratios are documented below.",
        "Seriatim is one selected-step row per policy; policy-month exports use the keys.",
        "",
    ]
    registry = ProductRegistry.default()
    for code in registry.codes():
        factory = registry.for_code(code)
        schema = factory.output_schema("Valuation")
        lines += [
            f"## {code}",
            "",
            "| Output | Source | Basis | Role / step |",
            "|---|---|---|---|",
        ]
        for role, entries in (("key", schema.keys), ("aggregate / policy-month", schema.entries)):
            for name, source, basis in entries:
                lines.append(f"| `{name}` | `{source}` | {basis or '-'} | {role} |")
        for name, source, basis, step in schema.seriatim:
            lines.append(f"| `{name}` | `{source}` | {basis or '-'} | seriatim step {step} |")
        lines += [
            "",
            "Book ratio columns (held numerator / eligible lives; sign shown):",
            "",
            "| Output | Numerator | Denominator | Basis | Sign |",
            "|---|---|---|---|---|",
        ]
        for name, (numerator, denominator, basis, sign) in factory.aggregate_ratios(schema).items():
            lines.append(f"| `{name}` | `{numerator}` | `{denominator}` | {basis} | {sign:g} |")
        lines += [""]
    # Dynamic reporting tables have no standalone schema class. Read only public
    # Parquet headers, never their numerical values; preserve writer order.
    home = ROOT / "tests/saved/demo/10000/TERM"
    for mode in ("cases", "capital", "measurement", "rollforward"):
        lines += [f"## Term {mode} reporting tables", ""]
        for path in sorted((home / mode).rglob("*.parquet"), key=lambda path: path.as_posix()):
            columns = list(pl.read_parquet_schema(path))
            if mode == "measurement" and "aggregate" in path.name:
                columns = [c for c in columns if c.startswith("IFRS17_")]
            elif mode == "rollforward" and path.name != "IFRS17_rollforward.parquet":
                continue
            lines += [f"### {path.name}", "", ", ".join(f"`{c}`" for c in columns), ""]
    lines += [
        "Other products use the same IFRS17 and bridge measure labels; capital risk labels",
        "come from the selected stress set and can include morbidity for riders.",
        "The generated dynamic list above describes the public Term demo, not arbitrary",
        "plug-in outputs. The selected factory and run record identify the actual contract.",
        "",
    ]
    result["output-columns.md"] = "\n".join(lines)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in pages().items():
        path = ROOT / "docs/reference" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale generated pages: " + ", ".join(stale))
    print("Reference pages current" if args.check else "Reference pages generated")


if __name__ == "__main__":
    main()
