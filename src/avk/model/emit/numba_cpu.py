"""The Numba CPU kernel module: helpers, two stage functions per pass, `project_one` and the
two drivers, as one source text (one file per kernel, so a cache never mixes versions).

Stage functions and helpers are the plain scalar subset shared with the GPU and pure Python.
Each pass has a scenario-independent part `stage_<k>i`, computed once per policy into
`oi (NI, M)`, and a scenario-dependent part `stage_<k>d`, computed for the `ns` scenarios of a
tile starting at `s0` into `od (ND, M, tile)` by an inner loop over the tile (the scenarios
run as vectors, not as one projection each). `project_one` runs every independent part, then
every dependent part; an independent column never reads a dependent one.

The drivers are CPU-specific: `prange` over work items (scenario tile, logical block of `BLOCK`
policies of the current batch `[lo, hi)`), each adding its policies in input order into its
block's accumulator `part[s, b]`, skipping NaN like `np.nansum`. A block that straddles two
batches continues where it stopped, so neither threads, tiles nor batch sizes change a bit.

Arguments, in order: `fld (NF, P)` fields, `key (NK, P)` dense keymap indices, `ist (NI,)`
integer-axis starts, `prm (NP,)` product parameters then run parameters, `scn (NS, S, M)`
scenario variables, one array per table, one monthly schedule `cv<j> (n,)` per curve, then `M`;
the drivers take the scenario tile size `st` after them.
"""

from avk.model.arithmetic import FMA_SUPPORT
from avk.model.emit.common import BLOCK, HELPER_NAMES, HELPERS, Layout, Stage
from avk.model.ir import Call, ProductIR, walk

DECORATOR = '_jit = numba.njit(error_model="numpy", cache=True)'
DRIVER = 'numba.njit(error_model="numpy", cache=True, parallel=True)'


def _arguments(layout: Layout) -> str:
    tables = "".join(f", tb{index}" for index in range(len(layout.tables)))
    curves = "".join(f", cv{index}" for index in range(len(layout.curves)))
    return f"fld, key, ist, prm, scn{tables}{curves}, M"


def _stage(ir: ProductIR, layout: Layout, index: int, part: str) -> list[str]:
    stage = ir.passes[index]
    emitter = Stage(ir, layout, stage, part)
    if not emitter.members:
        return []
    body = emitter.body()
    months = "range(M - 1, -1, -1)" if stage.direction == "backward" else "range(M)"
    lines = [f"def stage_{index}{part}(oi, od, s0, ns, i, {_arguments(layout)}):"]
    lines += [f"    f{j} = fld[{j}, i]" for j in range(len(layout.fields))]
    lines += [f"    k{j} = key[{j}, i]" for j in range(len(layout.keymaps))]
    lines += [f"    p{j} = prm[{j}]" for j in range(len(layout.params) + len(layout.run_params))]
    lines += [f"    for t in {months}:", "        tf = float(t)"]
    if part == "d":
        lines += ["        for u in range(ns):"]
        lines += [f"            {line}" for line in body]
    else:
        lines += [f"        {line}" for line in body]
    return ["", "", *lines, f"stage_{index}{part} = _jit(stage_{index}{part})"]


def emit(ir: ProductIR) -> tuple[str, Layout]:
    """The kernel module's source and the layout of its arguments."""
    layout = Layout.of(ir)
    args = _arguments(layout)
    lines = [
        f'"""Generated by Actuary Valuation Kit for {ir.code} on bases {", ".join(ir.bases)}."""',
        "",
        "import math",
        "",
        "import numba",
        "import numpy as np",
        "",
        DECORATOR,
        f"NI = {layout.independent}",
        f"ND = {len(layout.columns) - layout.independent}",
        f"BLOCK = {BLOCK}",
        HELPERS,
    ]
    if any(
        isinstance(node, Call) and node.fn == "fma" for q in ir.quantities for node in walk(q.expr)
    ):
        lines += [
            "from llvmlite import ir as llvm_ir",
            "from numba import types",
            "from numba.extending import intrinsic, overload",
            FMA_SUPPORT,
        ]
    lines += [f"{name} = _jit({name})" for name in HELPER_NAMES]
    calls = []
    for part in ("i", "d"):
        for index in range(len(ir.passes)):
            stage = _stage(ir, layout, index, part)
            lines += stage
            if stage:
                calls.append(f"    stage_{index}{part}(oi, od, s0, ns, i, {args})")
    lines += ["", "", f"def project_one(oi, od, s0, ns, i, {args}):", *calls]
    if not calls:
        lines.append("    pass")
    lines += ["", "", "project_one = _jit(project_one)"]
    lines += _drivers(args)
    return "\n".join(lines) + "\n", layout


def _drivers(args: str) -> list[str]:
    head = [
        "    S = part.shape[0]",
        "    nt = (S + st - 1) // st",
        "    b0 = lo // BLOCK",
        "    nb = (hi - 1) // BLOCK - b0 + 1",
        "    for w in numba.prange(nt * nb):",
        "        s0 = (w // nb) * st",
        "        ns = min(st, S - s0)",
        "        b = b0 + w % nb",
        "        oi = np.empty((NI, M))",
        "        od = np.empty((ND, M, st))",
        "        for i in range(max(lo, b * BLOCK), min(hi, (b + 1) * BLOCK)):",
        f"            project_one(oi, od, s0, ns, i, {args})",
        "            for c in range(out_idx.shape[0]):",
        "                r = out_idx[c]",
        "                if r < NI:",
        "                    for t in range(M):",
        "                        v = oi[r, t]",
        "                        if v == v:",
        "                            for u in range(ns):",
        "                                part[s0 + u, b, c, t] += v",
        "                else:",
        "                    for t in range(M):",
        "                        for u in range(ns):",
        "                            v = od[r - NI, t, u]",
        "                            if v == v:",
        "                                part[s0 + u, b, c, t] += v",
    ]
    rows = [
        "            for g in range(grid_idx.shape[0]):",
        "                r = grid_idx[g]",
        "                for u in range(ns):",
        "                    for t in range(M):",
        "                        if r < NI:",
        "                            grid_out[s0 + u, g, i - lo, t] = oi[r, t]",
        "                        else:",
        "                            grid_out[s0 + u, g, i - lo, t] = od[r - NI, t, u]",
        "            for k in range(sel_idx.shape[0]):",
        "                r = sel_idx[k]",
        "                for u in range(ns):",
        "                    if r < NI:",
        "                        sel_out[s0 + u, k, i] = oi[r, sel_step[k]]",
        "                    else:",
        "                        sel_out[s0 + u, k, i] = od[r - NI, sel_step[k], u]",
    ]
    return [
        "",
        "",
        f"def run_aggregate(lo, hi, {args}, st, out_idx, part):",
        *head,
        "",
        "",
        f"def run_rows(lo, hi, {args}, st, out_idx, part, grid_idx, grid_out, sel_idx, sel_step, "
        "sel_out):",
        *head,
        *rows,
        "",
        "",
        f"run_aggregate = {DRIVER}(run_aggregate)",
        f"run_rows = {DRIVER}(run_rows)",
    ]
